def _read(path) -> str:
    try:
        return path.read_text(encoding="utf-8")
    except Exception:
        return ""


def _skill_text() -> str:
    p = config.post_writer_skill_path()
    return _read(p) if p else ""


def build_system(platform: str) -> str:
    voice = _read(config.VOICE_FILE)
    identity = _read(config.IDENTITY_FILE)
    skill = _skill_text()
    plat = PLATFORMS.get(platform, PLATFORMS["linkedin"])

