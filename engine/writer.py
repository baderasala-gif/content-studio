def research(topic: str, content: str) -> dict:
    user = f"הנושא: {topic.strip()}\n"
    if content and content.strip():
        user += f"\nהקשר והכוונה של הכותב (לכוון את החיפוש, לא עובדות מאומתות):\n{content.strip()}\n"
    tools = [{"type": "web_search_20260209", "name": "web_search", "max_uses": 8}]
    res = claude.run(RESEARCH_SYSTEM, [{"role": "user", "content": user}], tools=tools,
                     max_tokens=16000, effort="high")

    sources: list[dict] = []
    seen: set[str] = set()
    for b in res["blocks"]:
        if b.get("type") == "web_search_tool_result":
            content_b = b.get("content")
            if isinstance(content_b, list):
                for r in content_b:
                    url = r.get("url")
                    if url and url not in seen:
                        seen.add(url)
                        sources.append({"title": r.get("title") or url, "url": url,
                                        "age": r.get("page_age")})
        elif b.get("type") == "text":
            for c in b.get("citations") or []:
                url = c.get("url")
                if url and url not in seen:
                    seen.add(url)
                    sources.append({"title": c.get("title") or url, "url": url, "age": None})
    return {"brief": res["text"], "sources": sources, "usage": res["usage"]}


def write_post(topic: str, content: str, platform: str, *, research_brief: str | None = None,
               previous: str | None = None) -> dict:
    if not topic.strip() and not (content or "").strip():
        raise claude.ClaudeError("חסר נושא או תוכן לפוסט.")
    system = build_system(platform)
    plat_label = PLATFORMS.get(platform, PLATFORMS["linkedin"])["label"]

    user = [f"כתוב פוסט ל{plat_label}.", f"הנושא: {topic.strip() or '(לא נמסר; ראה התוכן)'}",
            "בריף: הפוסט אינו 'לרמות' אלא אם נכתב כך בתוכן; שפה: עברית אלא אם נכתב אחרת בתוכן; "
            "מצב קהל: לפי הנושא."]
    if content and content.strip():
        user.append("התוכן, הנקודות והדוגמאות שבאדר מסר (זה החומר המרכזי, שמור על הפרטים שלו):\n"
                    + content.strip())
    if research_brief:
        user.append(
            "תקציר מחקר ממקורות שנבדקו. אפשר להשתמש רק בעובדות שמופיעות כאן. אין לציין מספרי מקור "
            "בגוף הפוסט; אפשר לציין את שם הגוף המפרסם בטבעיות (למשל 'לפי ארגון הבריאות העולמי'). "
            "עובדה שאינה כאן ואינה בתוכן שבאדר מסר, לא נכנסת לפוסט:\n" + research_brief
        )
    else:
        user.append("לא בוצע מחקר. אל תוסיף נתונים, מספרים, שמות או מחקרים שלא הופיעו בתוכן שנמסר.")
    if previous:
        user.append("גרסה קודמת שבאדר ביקש לנסח מחדש. כתוב גרסה שונה מהותית בפתיח, במבנה ובזווית, "
                    "באותו קול ועם אותם עובדות:\n" + previous)
    user.append("החזר את טקסט הפוסט בלבד.")

    res = claude.run(system, [{"role": "user", "content": "\n\n".join(user)}],
                     max_tokens=8000, effort="high")
    text, report = textrules.enforce(res["text"])
    if not text:
        raise claude.ClaudeError("Claude החזיר פוסט ריק. נסה שוב.")
    return {"text": text, "enforcement": report, "usage": res["usage"], "model": res["model"]}
